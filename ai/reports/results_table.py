"""Write ai/reports/RESULTS.md from metrics.json and model-comparison.md.

Keeps the human-readable table in lockstep with the numbers verify/ checks,
so nobody has to retype a figure after retraining.

    python ai/reports/results_table.py
"""
from __future__ import annotations

import datetime as dt
import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
METRICS = HERE / "metrics.json"
COMPARISON = HERE / "model-comparison.md"
OUT = HERE / "RESULTS.md"


def git_short_sha() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, text=True).strip()
    except Exception:
        return "unknown"


def main() -> None:
    m = json.loads(METRICS.read_text())
    report = m["test_classification_report"]
    today = dt.date.today().isoformat()

    lines = [
        "# Results",
        "",
        "Generated by `ai/reports/results_table.py` from `metrics.json`; don't edit by hand.",
        "All figures are on the synthetic set (`ai/data/DATASET.md`), so read them as",
        "'how separable the generator made its classes', not as accuracy on a mouse.",
        "",
        "## Production model",
        "",
        "| | |",
        "|---|---|",
        "| Model | HistGradientBoostingClassifier (max_iter 400, lr 0.06, depth 8) |",
        "| Data | `ai/data/synthetic.csv`, generator seed 42 |",
        "| Split | stratified by row, seed 42 |",
        f"| Rows | train {m['n_train']:,} / val {m['n_val']:,} / test {m['n_test']:,} |",
        f"| Val macro-F1 | {m['val_macro_f1']:.4f} |",
        f"| Test macro-F1 | {m['test_macro_f1']:.4f} |",
        f"| Test accuracy | {report['accuracy']:.4f} |",
        f"| Written | {today}, commit `{git_short_sha()}` |",
        "",
        "## Per class (test split)",
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|---|---:|---:|---:|---:|",
    ]
    for cls in m["classes"]:
        r = report[cls]
        lines.append(f"| {cls} | {r['precision']:.3f} | {r['recall']:.3f} | {r['f1-score']:.3f} | {int(r['support'])} |")

    lines += ["", "## Confusion matrix (rows = true, columns = predicted)", ""]
    classes = m["classes"]
    lines.append("| | " + " | ".join(classes) + " |")
    lines.append("|---|" + "---:|" * len(classes))
    for cls, row in zip(classes, m["test_confusion_matrix"]):
        lines.append(f"| **{cls}** | " + " | ".join(str(v) for v in row) + " |")

    if COMPARISON.exists():
        table = re.search(r"(\| Model.*?)(?:\n\n|\Z)", COMPARISON.read_text(), re.S)
        if table:
            lines += ["", "## Model comparison (`compare_models.py`, 80/20 split, seed 0)", "", table.group(1).strip()]

    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "make train     # ~1 min on a laptop; rewrites metrics.json and this file",
        "make verify    # recomputes the numbers above in eight languages",
        "```",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
